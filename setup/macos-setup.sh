#!/bin/bash
# Builds Organizer.app for macOS: a double-clickable app that runs launcher.py with
# python3 and no Terminal window, with the icon made from static/icon.png.
#
#   bash setup/macos-setup.sh [--python /path/to/python3] [--no-desktop-link]
#
# The app goes to ~/Applications/Organizer.app; a link to it is put on the Desktop unless
# --no-desktop-link is given. Re-running the script rebuilds both from scratch, so run it
# again after moving the repo folder or changing Python.
#
# Uses only tools that ship with macOS: osacompile, sips, iconutil, PlistBuddy, xattr,
# codesign, and python3 (the Xcode Command Line Tools one, or any other 3.9+).

set -euo pipefail

die()  { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
info() { printf '%s\n' "$*"; }

usage() {
    sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
}

# ---- options -------------------------------------------------------------------------
PYTHON=""
DESKTOP_LINK=1
while [ $# -gt 0 ]; do
    case "$1" in
        --python)          [ $# -ge 2 ] || die "--python needs a path"; PYTHON="$2"; shift 2 ;;
        --no-desktop-link) DESKTOP_LINK=0; shift ;;
        -h|--help)         usage; exit 0 ;;
        *)                 die "unknown option: $1 (see --help)" ;;
    esac
done

[ "$(uname -s)" = "Darwin" ] || die "this script is for macOS only (on Windows use setup/windows-shortcut.ps1)."
[ -n "${HOME:-}" ] && [ -d "$HOME" ] || die "HOME is not set to an existing folder."

# ---- repo, resolved from this script's own location ----------------------------------
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
LAUNCHER="$REPO/launcher.py"
ICON_PNG="$REPO/static/icon.png"
[ -f "$LAUNCHER" ]        || die "launcher.py not found in $REPO"
[ -f "$REPO/server.py" ]  || die "server.py not found in $REPO"
[ -f "$ICON_PNG" ]        || die "static/icon.png not found in $REPO"
case "$REPO" in
    *'"'*|*'\'*) die "the repo path contains a double quote or a backslash: move it to a plain path ($REPO)" ;;
esac

# ---- tools ---------------------------------------------------------------------------
for tool in osacompile sips iconutil xattr; do
    command -v "$tool" >/dev/null 2>&1 || die "'$tool' not found: it ships with macOS, so PATH is probably broken."
done
PLISTBUDDY=/usr/libexec/PlistBuddy
[ -x "$PLISTBUDDY" ] || die "$PLISTBUDDY not found: it ships with macOS."

# ---- python3 -------------------------------------------------------------------------
if [ -z "$PYTHON" ]; then
    PYTHON="$(command -v python3 || true)"
    [ -n "$PYTHON" ] || die "python3 not found. Install the Xcode Command Line Tools (xcode-select --install) or Python 3.9+, then re-run."
fi
case "$PYTHON" in
    /*) ;;
    *)  PYTHON="$(cd "$(dirname "$PYTHON")" && pwd -P)/$(basename "$PYTHON")" ;;
esac
[ -x "$PYTHON" ] || die "not an executable: $PYTHON"
case "$PYTHON" in
    *'"'*|*'\'*) die "the python path contains a double quote or a backslash: $PYTHON" ;;
esac
# /usr/bin/python3 is only a stub until the Command Line Tools are installed: running it
# would open the install dialog instead of Python. Check first, and stop with a hint.
if [ "$PYTHON" = "/usr/bin/python3" ] && ! xcode-select -p >/dev/null 2>&1; then
    die "/usr/bin/python3 is the Command Line Tools stub and the tools are not installed.
       Run 'xcode-select --install' (about 1-2 GB, asks for confirmation), then re-run this script.
       Or pass another Python 3.9+ with --python /path/to/python3."
fi
"$PYTHON" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' 2>/dev/null \
    || die "$PYTHON is not Python 3.9 or later (or does not run): $("$PYTHON" --version 2>&1 || true)"
info "Repo:   $REPO"
info "Python: $PYTHON ($("$PYTHON" --version 2>&1))"

# ---- work folder ---------------------------------------------------------------------
WORK="$(mktemp -d "${TMPDIR:-/tmp}/organizer-setup.XXXXXX")" || die "cannot create a temp folder"
trap 'rm -rf "$WORK"' EXIT
APP_TMP="$WORK/Organizer.app"

# ---- 1. AppleScript applet -----------------------------------------------------------
# The paths are written into the script now, at build time: the app lives in
# ~/Applications, not in the repo, so it cannot find the repo by itself.
cat > "$WORK/organizer.applescript" <<APPLESCRIPT
-- Generated by setup/macos-setup.sh. Re-run that script if the repo folder moves.
on run
	set pythonPath to "$PYTHON"
	set launcherPath to "$LAUNCHER"
	try
		-- launcher.py starts server.py detached (own session, no stdio), waits for
		-- /api/ping, opens the browser and exits, so this call returns in a few seconds.
		do shell script quoted form of pythonPath & " " & quoted form of launcherPath & " > /dev/null"
	on error errMsg
		set hint to "If the repo folder was moved, run setup/macos-setup.sh again."
		display dialog "Organizer could not start." & return & return & errMsg & return & return & hint buttons {"OK"} default button "OK" with icon stop with title "Organizer"
	end try
end run
APPLESCRIPT

osacompile -o "$APP_TMP" "$WORK/organizer.applescript" \
    || die "osacompile failed to build the app (see the message above)."
[ -d "$APP_TMP/Contents/Resources" ] || die "osacompile did not produce an app bundle at $APP_TMP"

# ---- 2. Icon from static/icon.png ----------------------------------------------------
ICONSET="$WORK/Organizer.iconset"
mkdir -p "$ICONSET"
make_png() {  # size, output name
    sips -z "$1" "$1" "$ICON_PNG" --out "$ICONSET/$2" >/dev/null \
        || die "sips could not resize static/icon.png to $1 px"
}
make_png 16   icon_16x16.png
make_png 32   icon_16x16@2x.png
make_png 32   icon_32x32.png
make_png 64   icon_32x32@2x.png
make_png 128  icon_128x128.png
make_png 256  icon_128x128@2x.png
make_png 256  icon_256x256.png
make_png 512  icon_256x256@2x.png   # upscaled: the source is 256 px
make_png 512  icon_512x512.png
make_png 1024 icon_512x512@2x.png
iconutil -c icns -o "$WORK/applet.icns" "$ICONSET" || die "iconutil could not build the .icns"

RES="$APP_TMP/Contents/Resources"
PLIST="$APP_TMP/Contents/Info.plist"
cp "$WORK/applet.icns" "$RES/applet.icns"
# Recent macOS versions also put the default icon in Assets.car, named by CFBundleIconName,
# and that one wins over applet.icns: remove both so the custom icon is used.
rm -f "$RES/Assets.car"
"$PLISTBUDDY" -c "Delete :CFBundleIconName" "$PLIST" >/dev/null 2>&1 || true
"$PLISTBUDDY" -c "Set :CFBundleIconFile applet" "$PLIST" >/dev/null 2>&1 \
    || "$PLISTBUDDY" -c "Add :CFBundleIconFile string applet" "$PLIST" \
    || die "could not set the icon in Info.plist"

# Changing the bundle breaks the ad-hoc signature osacompile made: sign it again (ad hoc,
# no Apple ID). Apple Silicon refuses to run code with an invalid signature.
xattr -cr "$APP_TMP" 2>/dev/null || true
if command -v codesign >/dev/null 2>&1; then
    codesign --force --deep --sign - "$APP_TMP" >/dev/null 2>&1 \
        || warn "codesign failed: if the app does not open, see 'Troubleshooting' in SETUP.md."
else
    warn "codesign not found: the app may not open on Apple Silicon (see SETUP.md)."
fi

# ---- 3. Install in ~/Applications (replacing any previous build) ---------------------
DEST_DIR="$HOME/Applications"
DEST="$DEST_DIR/Organizer.app"
mkdir -p "$DEST_DIR" || die "cannot create $DEST_DIR"
if [ -e "$DEST" ] || [ -L "$DEST" ]; then
    rm -rf "$DEST" || die "cannot remove the previous $DEST (is the app running?)"
fi
mv "$APP_TMP" "$DEST" || die "cannot move the app to $DEST"
touch "$DEST"   # nudges Finder to refresh the icon
info "App:    $DEST"

# ---- 4. Desktop link (optional) ------------------------------------------------------
if [ "$DESKTOP_LINK" -eq 1 ]; then
    LINK="$HOME/Desktop/Organizer"
    if [ -L "$LINK" ]; then
        rm -f "$LINK"
    fi
    if [ -e "$LINK" ]; then
        warn "$LINK exists and is not a link: left alone, no Desktop link made."
    elif ln -s "$DEST" "$LINK" 2>/dev/null; then
        info "Link:   $LINK -> $DEST"
    else
        warn "could not create $LINK (Desktop access denied?). The app works anyway from ~/Applications."
    fi
fi

info ""
info "Done. Start Organizer with:  open \"$DEST\""
info "Stop it with the power button in the page, or:  curl -s -X POST http://127.0.0.1:8765/api/shutdown"
